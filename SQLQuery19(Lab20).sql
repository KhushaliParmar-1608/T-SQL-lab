--From the table STUDENT perform the following queries:  
SELECT * FROM STUDENT

--Part – A: 

--1. Display rank of students based on SPI. 
SELECT STDID, SNAME , CITY , SPI , BRANCH,
RANK()OVER(ORDER BY SPI DESC) AS STD_RANK
FROM STUDENT

--2. Display dense rank of students based on SPI. 
SELECT STDID, SNAME , CITY , SPI , BRANCH,
DENSE_RANK()OVER(ORDER BY SPI DESC) AS STD_RANK
FROM STUDENT

--3. Display sequential number for each student record.
SELECT STDID, SNAME , CITY , SPI , BRANCH,
ROW_NUMBER()OVER(ORDER BY SPI DESC) AS STD_RANK
FROM STUDENT

--4. Display branch-wise rank of students. 
SELECT STDID, SNAME , CITY , SPI , BRANCH,
RANK()OVER(
PARTITION BY BRANCH
ORDER BY SPI DESC) AS STD_RANK
FROM STUDENT

--5. Display branch-wise dense ranking of students.
SELECT STDID, SNAME , CITY , SPI , BRANCH,
DENSE_RANK()OVER(
PARTITION BY BRANCH
ORDER BY SPI DESC) AS STD_RANK
FROM STUDENT

--6. Display branch-wise sequential numbering of students. 
SELECT STDID, SNAME , CITY , SPI , BRANCH,
ROW_NUMBER()OVER(
PARTITION BY BRANCH
ORDER BY SPI DESC) AS STD_RANK
FROM STUDENT

--7. Display SNAME, Current SPI, Previous SPI and SPI Difference with previous student in ascending order of 
--SPI. 
SELECT SNAME , SPI , 
LAG(SPI)OVER(ORDER BY SPI) AS PREVIOUS_SPI, 
SPI-LAG(SPI)OVER(ORDER BY SPI) AS DIFFERENCE_OF_SPI
FROM STUDENT
ORDER BY SPI ASC

--8. Display SNAME, Current SPI, Next SPI and SPI Difference with next student in descending order of SPI.
SELECT SNAME , SPI , 
LEAD(SPI)OVER(ORDER BY SPI DESC) AS NEXT_SPI, 
SPI-LEAD(SPI)OVER(ORDER BY SPI DESC) AS DIFFERENCE_OF_SPI
FROM STUDENT
ORDER BY SPI DESC

--9. Display top 3 students based on SPI. 
SELECT * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	ROW_NUMBER()OVER(ORDER BY SPI DESC) AS STD_RANK
	FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK <=3

--10. Display top 2 students from each branch. 
 SELECT * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	ROW_NUMBER()OVER(
				PARTITION BY BRANCH
				ORDER BY SPI DESC) AS STD_RANK
	FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK <=2

--Part – B: 
--11. Display 5th highest SPI. 
SELECT *
FROM
(
    SELECT STDID, SNAME, CITY, SPI, BRANCH,
           DENSE_RANK() OVER(ORDER BY SPI DESC) AS STD_RANK
    FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK = 5

--12. Display 6th highest SPI.
SELECT *
FROM
(
    SELECT STDID, SNAME, CITY, SPI, BRANCH,
           DENSE_RANK() OVER(ORDER BY SPI DESC) AS STD_RANK
    FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK = 6

--13. Display students having same ranking. 
 SELECT * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	RANK()OVER(ORDER BY SPI DESC) AS STD_RANK,
	COUNT(STDID)OVER(PARTITION BY SPI) AS CNT
	FROM STUDENT
) AS RANK_TABLE
WHERE CNT>1

--14. Display SNAME, Previous SPI, Current SPI and Next SPI based on ascending order of SPI. 
SELECT SNAME , 
LAG(SPI)OVER(ORDER BY SPI ASC) AS PRV_SPI,
SPI,
LEAD(SPI)OVER(ORDER BY SPI ASC) AS NEXT_SPI
FROM STUDENT

--15. Display topper of each branch. 
 SELECT * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	ROW_NUMBER()OVER(
				PARTITION BY BRANCH
				ORDER BY SPI DESC) AS STD_RANK
	FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK =1

--Part – C: 
--16. Display students whose SPI is greater than the previous student and less than the next student. 
SELECT SNAME, SPI
FROM (
    SELECT 
        SNAME,
        SPI,
        LAG(SPI) OVER (ORDER BY SPI) AS PREVIOUS_SPI,
        LEAD(SPI) OVER (ORDER BY SPI) AS NEXT_SPI
    FROM STUDENT
) AS T
WHERE SPI > PREVIOUS_SPI
  AND SPI < NEXT_SPI;


--17. Display branch-wise second topper students. 
SELECT * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	ROW_NUMBER()OVER(
				PARTITION BY BRANCH
				ORDER BY SPI DESC) AS STD_RANK
	FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK =2

--18. Display students whose rank and dense rank are different.
 SELECT * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	RANK()OVER(ORDER BY SPI DESC) AS STD_RANK,
	DENSE_RANK()OVER(ORDER BY SPI DESC) AS STD_DENCERANK
	FROM STUDENT
) AS RANK_TABLE
WHERE STD_RANK != STD_DENCERANK

--19. Display consecutive students having same branch ordered by SPI. 
SELECT SNAME, BRANCH, SPI
FROM
(
    SELECT 
        SNAME,
        BRANCH,
        SPI,
        LAG(BRANCH) OVER (ORDER BY SPI) AS PREVIOUS_BRANCH
    FROM STUDENT
) AS TABLE_NAME
WHERE BRANCH = PREVIOUS_BRANCH
ORDER BY SPI;

--20. Display students whose SPI difference with previous student is maximum.
 SELECT TOP 1 * FROM(
	SELECT STDID, SNAME , CITY , SPI , BRANCH,	
	SPI-LAG(SPI)OVER(ORDER BY SPI ) AS DIFF
	FROM STUDENT
) AS RANK_TABLE
ORDER BY DIFF DESC

