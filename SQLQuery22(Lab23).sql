--1. INSERT Procedures: Create stored procedures to insert records into STUDENT tables 
--(SP_INSERT_STUDENT) 

CREATE OR ALTER PROC SP_INSERT_STUDENT
@STDID INT,
@SNAME VARCHAR(20),
@CITY VARCHAR(20),
@SPI DECIMAL(4,2),
@BRANCH VARCHAR(20)
AS
BEGIN
    INSERT INTO STUDENT
    VALUES(@STDID , @SNAME , @CITY , @SPI , @BRANCH)
END

